import { formatCurrency } from '../constants/currency';
import { APP_NAME } from '../constants/brand';
import type { BudgetStat, DailyTrendPoint, SpendingSlice } from './index';

export type ReportPeriod = 'daily' | 'weekly' | 'monthly' | 'yearly';

export type ReportPeriodRange = {
  period: ReportPeriod;
  start: string;
  end: string;
  label: string;
};

function pad2(value: number): string {
  return String(value).padStart(2, '0');
}

function toIsoDay(date: Date): string {
  return `${date.getFullYear()}-${pad2(date.getMonth() + 1)}-${pad2(date.getDate())}`;
}

function startOfWeekMonday(date: Date): Date {
  const result = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  const day = result.getDay(); // 0 Sun .. 6 Sat
  const diff = day === 0 ? -6 : 1 - day;
  result.setDate(result.getDate() + diff);
  return result;
}

export function getReportPeriodRange(
  period: ReportPeriod,
  anchor: Date = new Date()
): ReportPeriodRange {
  const base = new Date(anchor.getFullYear(), anchor.getMonth(), anchor.getDate());

  if (period === 'daily') {
    const iso = toIsoDay(base);
    return {
      period,
      start: iso,
      end: iso,
      label: base.toLocaleDateString('en-PH', {
        weekday: 'long',
        month: 'long',
        day: 'numeric',
        year: 'numeric',
      }),
    };
  }

  if (period === 'weekly') {
    const start = startOfWeekMonday(base);
    const end = new Date(start);
    end.setDate(start.getDate() + 6);
    return {
      period,
      start: toIsoDay(start),
      end: toIsoDay(end),
      label: `Week of ${start.toLocaleDateString('en-PH', { month: 'short', day: 'numeric' })} – ${end.toLocaleDateString('en-PH', { month: 'short', day: 'numeric', year: 'numeric' })}`,
    };
  }

  if (period === 'yearly') {
    const start = new Date(base.getFullYear(), 0, 1);
    const end = new Date(base.getFullYear(), 11, 31);
    return {
      period,
      start: toIsoDay(start),
      end: toIsoDay(end),
      label: String(base.getFullYear()),
    };
  }

  const start = new Date(base.getFullYear(), base.getMonth(), 1);
  const end = new Date(base.getFullYear(), base.getMonth() + 1, 0);
  return {
    period: 'monthly',
    start: toIsoDay(start),
    end: toIsoDay(end),
    label: base.toLocaleString('en-PH', { month: 'long', year: 'numeric' }),
  };
}

